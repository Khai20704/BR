import type { PlanEnvelopePayload } from '@/core/api/backend-schemas'
import { isGeminiRecommendation, validationLabel } from './assessment'

export function Recommendations({
  plan,
  error,
  retry,
  busy = false,
}: {
  plan: PlanEnvelopePayload | null
  error: string
  retry?: () => void
  busy?: boolean
}) {
  const live = isGeminiRecommendation(plan?.narrative)
  return (
    <>
      <p
        className={
          'recommendation-source ' + (live ? 'verified-narrative' : '')
        }
      >
        {live
          ? 'Gemini recommendation · informed by recorded model tool calls'
          : 'Gemini recommendations unavailable'}
      </p>
      {error && (
        <div role="alert">
          <p>{error}</p>
          {retry && (
            <button
              className="button secondary"
              disabled={busy}
              onClick={retry}
            >
              {busy ? 'Requesting recommendation…' : 'Retry recommendation'}
            </button>
          )}
        </div>
      )}
      {plan ? (
        <>
          {!live && (
            <p className="body-copy">
              Showing a rule-based explanation returned by the drying model. It
              was not generated by Gemini.
            </p>
          )}
          <p className="narrative-copy">
            {plan.narrative.text.replace(
              /\b(?:NOT_VALIDATED|NO_FEASIBLE_PLAN|NEED_MORE_DATA|VALIDATED)\b/g,
              (status) => validationLabel(status).toLowerCase(),
            ) || 'No written explanation was returned.'}
          </p>
          {plan.plan.phases.length > 0 && (
            <ol className="plan-steps">
              {plan.plan.phases.map((phase, index) => (
                <li key={index}>
                  Plan step {index + 1}: {phase.temperature_c}°C for up to{' '}
                  {phase.duration_minutes} minutes.
                </li>
              ))}
            </ol>
          )}
          {plan.plan.phases.length > 0 && (
            <p className="body-copy">
              The schedule allows up to the stated duration. The prediction may
              reach your target earlier.
            </p>
          )}
        </>
      ) : (
        <p className="body-copy">
          The drying prediction is still available. An AI recommendation could
          not be retrieved.
        </p>
      )}
    </>
  )
}
